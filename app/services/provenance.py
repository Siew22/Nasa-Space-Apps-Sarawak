"""Read data statuses from reports/data_provenance_audit.json (written by src/provenance_audit.py).

Statuses are never assumed. If the report is missing or unreadable every dataset is treated as
UNVERIFIED_SOURCE and a warning says why, so callers cannot silently present data as verified.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
REPORT_PATH = ROOT / "reports" / "data_provenance_audit.json"

STATUS_VOCABULARY = {
    "VERIFIED_SOURCE": "Traced to an authoritative source file and rebuilt or checksum-matched.",
    "UNVERIFIED_SOURCE": "Cannot be traced to an authoritative source.",
    "SYNTHETIC_DEMO": "Generated by a script for demonstration; not a measurement.",
    "REAL_MEASUREMENT": "Measured values from a verified source.",
    "MODEL_PREDICTION": "Output of a trained model, not a measurement.",
    "SIMULATED_RESULT": "Output of the educational physics model, not a measurement or a learned prediction.",
    "NOT_EVALUATED": "No score was produced; see the stated reason.",
}
MISSING_WARNING = ("Provenance report reports/data_provenance_audit.json is missing or unreadable; "
                   "run `python -m src.provenance_audit`. All datasets are treated as UNVERIFIED_SOURCE.")


def load_report(path: Path | None = None) -> dict[str, Any] | None:
    path = path or REPORT_PATH
    try:
        report = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return report if isinstance(report, dict) and isinstance(report.get("datasets"), dict) else None


def dataset_status(dataset_key: str, report: dict[str, Any] | None = None, *, path: Path | None = None) -> dict[str, Any]:
    report = report if report is not None else load_report(path)
    if report is None:
        return {"dataset_key": dataset_key, "status": "UNVERIFIED_SOURCE", "result_type": "UNVERIFIED",
                "warning": MISSING_WARNING, "report_generated_at_utc": None}
    entry = report["datasets"].get(dataset_key)
    if not entry:
        return {"dataset_key": dataset_key, "status": "UNVERIFIED_SOURCE", "result_type": "UNVERIFIED",
                "warning": f"{dataset_key} is not covered by the provenance report.",
                "report_generated_at_utc": report.get("generated_at_utc")}
    status = entry.get("status", "UNVERIFIED_SOURCE")
    warning = None
    if status == "SYNTHETIC_DEMO":
        warning = f"{dataset_key} rows are synthetic demonstration data, not NASA measurements."
    elif status != "VERIFIED_SOURCE":
        warning = f"{dataset_key} cannot be traced to an authoritative source."
    return {"dataset_key": dataset_key, "status": status, "result_type": entry.get("result_type"),
            "rows": entry.get("rows"), "evidence_codes": [e.get("code") for e in entry.get("evidence", [])],
            "warning": warning, "report_generated_at_utc": report.get("generated_at_utc")}
