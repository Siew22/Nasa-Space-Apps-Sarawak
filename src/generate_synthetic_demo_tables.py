"""Generate SYNTHETIC demonstration tables in the NASA PSI-25 (BASS-II) and PSI-69 (FLEX) column format.

Every value below is produced by a formula. Nothing here is downloaded from NASA and
nothing here is a measurement. The tables exist only so the dashboard has something
to display until the real PSI experimental tables are obtained (see
reports/data_provenance_audit.json for what is missing).

Previously this script was named download_nasa_tables.py and wrote to
data/raw/PSI-*_experimental_table.csv with a "NASA ... Experimental Table" note,
which made generated rows look like NASA records. Output now goes to data/demo/
with explicit file names and notes; the generated values are unchanged.
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEMO_DIR = ROOT / "data" / "demo"
FLEX_FILE = "SYNTHETIC_DEMO_FLEX_PSI-69_format.csv"
BASS_FILE = "SYNTHETIC_DEMO_BASS_II_PSI-25_format.csv"
SYNTHETIC_NOTE = ("SYNTHETIC DEMO: formula-generated by src/generate_synthetic_demo_tables.py; "
                  "not a NASA measurement")


def generate_flex_dataset(out_dir: Path = DEMO_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / FLEX_FILE
    cols = [
        "FLEX Test #", "FLEX Identifier", "Test Date", "Test GMT", "Fuel",
        "Ambient pressure; mmHg", "O initial ambient composition; mole fraction",
        "N initial ambient composition; mole fraction", "CO initial ambient composition; mole fraction",
        "He initial ambient composition; mole fraction", "Droplet initial diameter; mm",
        "Visible flame extinction diameter; mm", "Burning rate; mm", "Burn time; s", "Test end",
        "source_url", "source_note"
    ]
    fuels = ["Methanol", "Heptane", "Octane"]
    outcomes = ["Extinction", "Disruption", "Extinction", "Extinction"]

    with open(target, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(cols)
        for i in range(1, 41):
            d0 = round(1.50 + (i * 0.04) % 1.2, 2)
            d_ext = round(d0 * (0.45 + (i % 3) * 0.05), 2)
            writer.writerow([
                i,
                f"CAL_{i:02d}",
                f"2009-03-{10 + (i % 15):02d}",
                f"1{i % 10}:20:00",
                fuels[i % len(fuels)],
                round(750.0 + (i % 5) * 5.2, 1),
                round(0.18 + (i % 4) * 0.03, 2),
                round(0.82 - (i % 4) * 0.03, 2),
                0.0,
                0.0,
                d0,
                d_ext,
                round(0.40 + (i % 6) * 0.05, 2),
                round(3.0 + (i * 0.25) % 6.0, 2),
                outcomes[i % len(outcomes)],
                "",
                SYNTHETIC_NOTE,
            ])
    print(f"Wrote SYNTHETIC demo FLEX-format table (40 generated rows, not NASA data): {target}")
    return target


def generate_bass_dataset(out_dir: Path = DEMO_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / BASS_FILE
    cols = [
        "PI", "Test #", "Date", "GMT", "Sample #", "Fuel Sample Material",
        "Flow restrictor", "Fan display", "Air display", "Radiometer gain (1000 250 50 10)",
        "Total Frames Shot", "Calibrated initial O2 % by vol", "Calibrated final O2 % by vol",
        "Initial CO2 % by vol", "Final CO2 % by vol", "Initial CO (ppm)", "Final CO (ppm)",
        "source_url", "source_note"
    ]
    materials = [
        "100 micron PMMA film 2 cm wide",
        "200 micron PMMA film 2 cm wide",
        "300 micron PMMA film 2 cm wide",
        "Cotton-Fiberglass SIBAL Fabric",
        "Delrin Hemispherical Rod"
    ]

    with open(target, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(cols)
        for i in range(1, 41):
            o2_init = round(21.0 + (i % 5) * 1.5, 1)
            writer.writerow([
                "Bhattacharjee",
                f"B{i}",
                "2014-02-19",
                50 + i,
                100 + i,
                materials[i % len(materials)],
                2,
                45 + (i % 6) * 5,
                5,
                50,
                100 + i * 5,
                o2_init,
                round(o2_init - (0.2 + (i % 4) * 0.1), 1),
                0.44,
                0.52,
                i % 3,
                (i % 3) + 5 + (i % 10),
                "",
                SYNTHETIC_NOTE,
            ])
    print(f"Wrote SYNTHETIC demo BASS-II-format table (40 generated rows, not NASA data): {target}")
    return target


if __name__ == "__main__":
    generate_flex_dataset()
    generate_bass_dataset()